import { session, openProject, openModel, open3D, browser } from './lib.mjs';
await session('07-schedule-isolate', async (T) => {
  const { cap, click, p, pane, dlg, wait } = T; const D = () => dlg();
  await T.top('#tabs [data-tab="DWFx Measure"]', 300); await T.top('#ribbon [data-fn=openProjects]', 800);
  await openProject(T); await openModel(T);
  await cap('Schedules you add to Excel stay linked to the 3D model. First, restore your saved take-off groups into this workbook.', 3200);
  await click('[data-tab=project]', 800); await click('[data-sec=takeoffs]', 800); await click('#toRestoreAll', 3000);
  const rows = await pane().evaluate(() => { const v = window.__sheet('Take-off'); const out = { el: [], grp: [] };
    v.forEach((r, i) => { if (/^G\d+\.\d+$/.test(String(r[0]))) out.el.push([i + 1, r[0], r[3]]); else if (/^G\d+$/.test(String(r[0]))) out.grp.push([i + 1, r[0]]); }); return out; });
  console.log('rows', JSON.stringify(rows).slice(0, 400));
  await cap('Open the 3D window and put it next to the sheet.', 2200);
  await open3D(T);
  await p.evaluate(() => window.__dlgPos(575, 112, 780, 610)); await wait(1500);
  await cap('Click a row number in the schedule. The element of that row is selected in the 3D model.', 3200);
  const r1 = rows.el[2][0];
  await T.top(`#grid th[data-row="${r1}"]`, 2500);
  await cap('Press Isolate in the 3D window: only that element stays visible.', 2400);
  await click('[data-t=isolate]', 2500, D);
  await click('[data-t=showall]', 1200, D);
  await cap('Select several rows (drag over the row numbers) to isolate a few elements together.', 3000);
  const r2 = rows.el[8] ? rows.el[8][0] : r1 + 4;
  await T.move(`#grid th[data-row="${r1}"]`, () => p.mainFrame()); await p.mouse.down(); await T.move(`#grid th[data-row="${r2}"]`, () => p.mainFrame()); await p.mouse.up();
  await p.evaluate(([a, b]) => window.__selectRows(a, b), [r1, r2]); await wait(2200);
  await click('[data-t=isolate]', 2500, D);
  await click('[data-t=showall]', 1200, D);
  await cap('Click the group row (G1, G2 ...) to select every element of that schedule, then Isolate.', 3200);
  await T.top(`#grid th[data-row="${rows.grp[0][0]}"]`, 2500);
  await click('[data-t=isolate]', 3000, D);
  await cap('The same works for BOQ items and schedules on any sheet that was made by DWFx Measure.', 3600);
  await click('[data-t=showall]', 1200, D);
});
await browser.close();
