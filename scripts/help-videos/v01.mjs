import { session, signIn, ribbon, openProject, DWFX, PROJECT, browser } from './lib.mjs';
await session('01-projects', async (T) => {
  const { cap, click, type, p, pane, find } = T;
  await cap('DWFx Measure works inside Excel. Open the DWFx Measure tab on the ribbon.', 2600);
  await T.top('#tabs [data-tab="DWFx Measure"]', 1200);
  await cap('Press Project & Models. The task pane opens on the right of your workbook. Sign in with the email and password from your administrator.', 3400);
  await T.top('#ribbon [data-fn=openProjects]', 1000);
  await signIn(T);
  await cap('Create a project for each job. Everything you upload is saved on the server for your team.', 2800);
  await click('#pNew'); await type('#npName', PROJECT); await type('#npCode', 'XXXXX'); await type('#npClient', 'Client name');
  await click('#npf .btn.primary', 1200);
  await cap('Upload the DWFx exported from Revit. Use the same model name again later to add version 2, 3 ...', 3000);
  await click('#upToggle'); await pane().setInputFiles('#upFile', DWFX); await T.wait(500);
  await pane().fill('#upName', ''); await type('#upName', 'Structure'); await pane().selectOption('#upDisc', 'Structure'); await T.wait(400);
  await cap('The model is processed on your own computer, so you do not wait for the server. Keep Excel open until it is Ready.', 3200);
  await click('#upGo', 1500);
  await cap('Progress is shown step by step. Large models take a few minutes.', 2400);
  await pane().waitForSelector('[data-open]', { timeout: 300000 });
  await cap('When the version shows Ready, press Open.', 1800);
  await click('[data-open]', 600);
  await pane().waitForFunction(() => window.__viewer?.n > 0, null, { timeout: 120000 }); await T.wait(1200);
  await cap('The 3D model opens in the task pane, the element browser below it. Tick a category, family or type to select it.', 3200);
  await click('#tree .node input[type=checkbox]', 1500);
  await cap('Right-click an element in 3D to see its properties and the exact quantities measured from the geometry.', 2600);
  const c = await pane().$eval('#vstage canvas', el => { const r = el.getBoundingClientRect(); return [r.x + r.width * 0.55, r.y + r.height * 0.55]; });
  const fb = await p.locator('#paneFrame').boundingBox();
  await p.mouse.move(fb.x + c[0], fb.y + c[1], { steps: 8 }); await p.mouse.click(fb.x + c[0], fb.y + c[1], { button: 'right' }); await T.wait(2800);
  await click('#pClose', 600);
}, { signedIn: false });
await browser.close();
