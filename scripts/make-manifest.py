"""Writes manifest.xml: the DWFx Measure ribbon tab (shared runtime). Run: python3 scripts/make-manifest.py [base-url]"""
import sys, os
from xml.sax.saxutils import escape
BASE = (sys.argv[1] if len(sys.argv) > 1 else 'https://dwfx-addin-production.up.railway.app').rstrip('/')
VERSION = '0.7.2.0'
G = [
 ('Measure', 'Measure', 'measure', [
   ('Meas', 'Measurements', 'group', 'openMeasurements', 'Show the dimension groups and their totals in the task pane.'),
   ('Window', 'Measurement Window', 'window', 'openMeasureWindow', 'Open the measurement window: ribbon, drawings, 3D model, dimension folders and groups.'),
   ('Projects', 'Projects', 'projects', 'openProjects', 'Open projects, models, drawings and project settings.')]),
 ('Links', 'Excel links', 'fromexcel', [
   ('Link', 'Link to Cell', 'fromexcel', 'linkToCell', 'Link a dimension group or a dimension to the selected cell with a live formula (=CX.QTY).'),
   ('Follow', 'Follow Excel', 'status', 'followExcel', 'On: a click on a linked cell shows where it was measured. The links always stay.'),
   ('Refresh', 'Refresh Links', 'refresh', 'refreshLinks', 'Read the linked cells and the measurements again.'),
   ('Share', 'Share Copy', 'update', 'shareCopy', 'For people without the add-in: linked cells become plain numbers (the formulas are kept). Then Save a Copy and Restore Links.'),
   ('Restore', 'Restore Links', 'compare', 'restoreLinks', 'Make the links live again after sharing a copy.')]),
 ('Schedules', 'DWFx schedules', 'boq', [
   ('Sched', 'DWFx Schedules', 'boq', 'openSchedules', 'Open the DWFx Schedules window: schedules from the model data, with the AI.')]),
]
icons = sorted({g[2] for g in G} | {c[2] for g in G for c in g[3]})
ic = lambda n: '\n'.join(f'                    <bt:Image size="{s}" resid="I.{n}.{s}"/>' for s in (16, 32, 80))
groups = []
for gid, glabel, gicon, ctrls in G:
    cs = []
    for cid, label, icon, fn, tip in ctrls:
        if cid == 'Meas':
            act = f'''                  <Action xsi:type="ShowTaskpane">
                    <TaskpaneId>DWFx.Taskpane</TaskpaneId>
                    <SourceLocation resid="PaneUrl"/>
                  </Action>'''
        else:
            act = f'''                  <Action xsi:type="ExecuteFunction"><FunctionName>{fn}</FunctionName></Action>'''
        cs.append(f'''                <Control xsi:type="Button" id="DWFx.{cid}">
                  <Label resid="L.{cid}"/>
                  <Supertip><Title resid="L.{cid}"/><Description resid="T.{cid}"/></Supertip>
                  <Icon>
{ic(icon)}
                  </Icon>
{act}
                </Control>''')
    groups.append(f'''              <Group id="DWFx.G.{gid}">
                <Label resid="G.{gid}"/>
                <Icon>
{ic(gicon)}
                </Icon>
{chr(10).join(cs)}
              </Group>''')
images = '\n'.join(f'        <bt:Image id="I.{n}.{s}" DefaultValue="{BASE}/assets/ribbon/{n}-{s}.png?v={VERSION}"/>' for n in icons for s in (16, 32, 80))
short = '\n'.join([f'        <bt:String id="G.{g[0]}" DefaultValue="{escape(g[1])}"/>' for g in G] + [f'        <bt:String id="L.{c[0]}" DefaultValue="{escape(c[1])}"/>' for g in G for c in g[3]]
                  + ['        <bt:String id="TabLabel" DefaultValue="DWFx Measure"/>', '        <bt:String id="FnNs" DefaultValue="CX"/>', '        <bt:String id="GetStarted.Title" DefaultValue="DWFx Measure is ready"/>'])
long = '\n'.join([f'        <bt:String id="T.{c[0]}" DefaultValue="{escape(c[4])}"/>' for g in G for c in g[3]]
                 + ['        <bt:String id="GetStarted.Description" DefaultValue="Open the DWFx Measure tab on the ribbon and choose Projects to sign in."/>'])
xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- DWFx Measure add-in (generated by scripts/make-manifest.py). Live address: {BASE}
     Ribbon tab "DWFx Measure" with a shared runtime: the task pane, the ribbon buttons and the custom functions
     (=CX.QTY, =CX.VALUE, =CX.NAME, =CX.UNIT) run in the same page. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1"
           xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
           xmlns:bt="http://schemas.microsoft.com/office/officeappbasictypes/1.0"
           xmlns:ov="http://schemas.microsoft.com/office/taskpaneappversionoverrides"
           xsi:type="TaskPaneApp">
  <Id>6f1c2a4e-8d3b-4f7a-9c51-2b7e0d4a9f13</Id>
  <Version>{VERSION}</Version>
  <ProviderName>QSGS</ProviderName>
  <DefaultLocale>en-US</DefaultLocale>
  <DisplayName DefaultValue="DWFx Measure"/>
  <Description DefaultValue="Measure drawings (PDF, DWG, DXF, DWFx) and 3D models in a CostX-style window, linked to Excel cells with live formulas, and make DWFx quantity schedules."/>
  <IconUrl DefaultValue="{BASE}/assets/icon-32.png?v={VERSION}"/>
  <HighResolutionIconUrl DefaultValue="{BASE}/assets/icon-64.png?v={VERSION}"/>
  <SupportUrl DefaultValue="{BASE}/"/>
  <AppDomains>
    <AppDomain>{BASE}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Workbook"/>
  </Hosts>
  <Requirements>
    <Sets DefaultMinVersion="1.9">
      <Set Name="ExcelApi" MinVersion="1.9"/>
    </Sets>
  </Requirements>
  <DefaultSettings>
    <SourceLocation DefaultValue="{BASE}/taskpane.html"/>
  </DefaultSettings>
  <Permissions>ReadWriteDocument</Permissions>
  <VersionOverrides xmlns="http://schemas.microsoft.com/office/taskpaneappversionoverrides" xsi:type="VersionOverridesV1_0">
    <Requirements>
      <bt:Sets DefaultMinVersion="1.1">
        <bt:Set Name="SharedRuntime" MinVersion="1.1"/>
      </bt:Sets>
    </Requirements>
    <Hosts>
      <Host xsi:type="Workbook">
        <Runtimes>
          <Runtime resid="PaneUrl" lifetime="long"/>
        </Runtimes>
        <DesktopFormFactor>
          <GetStarted>
            <Title resid="GetStarted.Title"/>
            <Description resid="GetStarted.Description"/>
            <LearnMoreUrl resid="PaneUrl"/>
          </GetStarted>
          <FunctionFile resid="PaneUrl"/>
          <ExtensionPoint xsi:type="PrimaryCommandSurface">
            <CustomTab id="DWFx.Tab">
{chr(10).join(groups)}
              <Label resid="TabLabel"/>
            </CustomTab>
          </ExtensionPoint>
        </DesktopFormFactor>
        <AllFormFactors>
          <ExtensionPoint xsi:type="CustomFunctions">
            <Script><SourceLocation resid="FnJs"/></Script>
            <Page><SourceLocation resid="PaneUrl"/></Page>
            <Metadata><SourceLocation resid="FnJson"/></Metadata>
            <Namespace resid="FnNs"/>
          </ExtensionPoint>
        </AllFormFactors>
      </Host>
    </Hosts>
    <Resources>
      <bt:Images>
{images}
      </bt:Images>
      <bt:Urls>
        <bt:Url id="PaneUrl" DefaultValue="{BASE}/taskpane.html"/>
        <bt:Url id="FnJs" DefaultValue="{BASE}/js/cxfunctions.js"/>
        <bt:Url id="FnJson" DefaultValue="{BASE}/functions.json"/>
      </bt:Urls>
      <bt:ShortStrings>
{short}
      </bt:ShortStrings>
      <bt:LongStrings>
{long}
      </bt:LongStrings>
    </Resources>
  </VersionOverrides>
</OfficeApp>
'''
out = os.path.join(os.path.dirname(__file__), '..', 'manifest.xml')
open(out, 'w').write(xml)
fns = sorted({c[3] for g in G for c in g[3]})
print('manifest', VERSION, 'buttons', sum(len(g[3]) for g in G), 'functions', len(fns)); print(' '.join(fns))
